import {
  resolveMargins,
  resolvePageSize,
} from '../Container/Hooks/useLayout.js';

/*
 * Generates the @page stylesheet from layout settings.
 *
 * This CSS is not for the browser — browsers ignore @top-center, string-set,
 * target-counter and the rest. It is fed to paged.js's Polisher, which parses
 * it and rewrites it into concrete .pagedjs_* rules. The same text is also
 * mirrored into <style id="wp-layout-styles"> so it is inspectable and so the
 * plain fragmentation properties (break-before, orphans) reach the live DOM.
 */

export const LAYOUT_STYLE_ID = 'wp-layout-styles';

/** Named sizes paged.js understands directly; anything else goes as mm. */
const NAMED_SIZES = new Set(['a3', 'a4', 'a5', 'letter', 'legal']);

/** CSS string literal: escape backslashes and double quotes. */
const cssString = (value) =>
  `"${String(value).replace(/\\/g, '\\\\').replace(/"/g, '\\"')}"`;

const TOKENS = {
  '{page}': 'counter(page)',
  '{pages}': 'counter(pages)',
  '{title}': 'string(doc-title)',
};

/**
 * Turns a user template into a CSS `content` value.
 *
 * `Page {page} of {pages}` becomes `"Page " counter(page) " of " counter(pages)`
 * — a sequence of literals and counter functions, not one big string. A naive
 * replace would produce `"Page counter(page) of counter(pages)"`, which prints
 * the function names.
 *
 * `{{` is a literal `{`. `{date}` resolves at build time because CSS has no way
 * to compute it.
 */
export function templateToContent(template, { date } = {}) {
  if (typeof template !== 'string' || template === '') return null;

  const today = date ?? new Date().toISOString().slice(0, 10);
  const parts = [];
  let literal = '';

  const flush = () => {
    if (literal !== '') {
      parts.push(cssString(literal));
      literal = '';
    }
  };

  let i = 0;
  while (i < template.length) {
    if (template.startsWith('{{', i)) {
      literal += '{';
      i += 2;
      continue;
    }
    if (template[i] === '{') {
      const close = template.indexOf('}', i);
      if (close !== -1) {
        const token = template.slice(i, close + 1);
        if (token === '{date}') {
          literal += today;
          i = close + 1;
          continue;
        }
        if (TOKENS[token]) {
          flush();
          parts.push(TOKENS[token]);
          i = close + 1;
          continue;
        }
      }
      // Unrecognised — treat as ordinary text rather than swallowing it.
      literal += '{';
      i += 1;
      continue;
    }
    literal += template[i];
    i += 1;
  }
  flush();

  return parts.length ? parts.join(' ') : cssString('');
}

/** One header or footer margin box, or '' when the template is empty. */
function marginBox(name, template, opts) {
  const content = templateToContent(template, opts);
  if (content === null) return '';
  return `  @${name} {
    content: ${content};
    font-family: var(--wp-font-family-sans);
    font-size: 9pt;
    color: var(--wp-color-fg-muted);
    vertical-align: middle;
  }
`;
}

export function generateLayoutCSS(layout, opts = {}) {
  const margins = resolveMargins(layout);
  const { width, height } = resolvePageSize(layout);

  // paged.js accepts a named size plus orientation; custom sizes must be
  // explicit dimensions, and orientation is applied by swapping them because
  // `210mm 297mm landscape` is not valid CSS.
  const size = NAMED_SIZES.has(layout.pageSize)
    ? `${layout.pageSize.toUpperCase()} ${layout.orientation}`
    : layout.orientation === 'landscape'
      ? `${height}mm ${width}mm`
      : `${width}mm ${height}mm`;

  const boxes =
    marginBox('top-left', layout.headerLeft, opts) +
    marginBox('top-center', layout.headerCenter, opts) +
    marginBox('top-right', layout.headerRight, opts) +
    marginBox('bottom-left', layout.footerLeft, opts) +
    marginBox('bottom-center', layout.footerCenter, opts) +
    marginBox('bottom-right', layout.footerRight, opts);

  let css = `/* Generated by generateLayoutCSS — do not edit by hand. */
@page {
  size: ${size};
  margin: ${margins.top}mm ${margins.right}mm ${margins.bottom}mm ${margins.left}mm;
${boxes}}

/* First H1 becomes the {title} placeholder's value. */
.markdown-body h1 { string-set: doc-title content(text); }

/* Fragmentation. */
.markdown-body h1 { break-before: page; }
.markdown-body h1:first-child { break-before: auto; }
.markdown-body h2,
.markdown-body h3,
.markdown-body h4 { break-after: avoid; }
.markdown-body pre,
.markdown-body blockquote,
.markdown-body img,
.markdown-body figure { break-inside: avoid; }
.markdown-body figure figcaption { break-before: avoid; }
.markdown-body .katex-display { break-inside: avoid; }
/* Tables get header repetition rather than break-inside:avoid — a table taller
   than the page would otherwise overflow instead of splitting. */
.markdown-body table { break-inside: auto; }
.markdown-body thead { display: table-header-group; }
.markdown-body tr { break-inside: avoid; }
.markdown-body p { orphans: 3; widows: 3; }

/* paged.js sizes the page box itself; a max-width here would double-constrain. */
.pagedjs_page_content .markdown-body { max-width: none; margin: 0; }
`;

  if (layout.cover.enabled) {
    css += `
/* Cover. Named page, so it is addressable independently of :first. */
.wp-cover-page { page: cover; break-after: page; }
@page cover {
  margin: 0;
  @top-left { content: none; }
  @top-center { content: none; }
  @top-right { content: none; }
  @bottom-left { content: none; }
  @bottom-center { content: none; }
  @bottom-right { content: none; }
}
/* The document's own first H1 must not add a second break after the cover. */
.wp-cover-page + .markdown-body > h1:first-child,
.wp-cover-page ~ * > h1:first-child { break-before: auto; }
`;
  }

  if (layout.toc.enabled) {
    /*
     * Two things that look like spec-compliant CSS but are not usable here,
     * kept as a source comment rather than emitted into every stylesheet:
     *
     * 1. leader('.') is in the Paged Media spec and implemented by neither
     *    paged.js nor any browser. An unrecognised function invalidates the
     *    entire `content` value, so using it silently removes the page numbers
     *    along with the dots. The dotted rule below is a flex filler instead,
     *    which is why buildToc wraps each label in its own span.
     * 2. target-counter(attr(href url), page) is the spec form, but paged.js
     *    collects every Identifier inside attr() as an argument, so `url`
     *    becomes a bogus second argument and the lookup returns nothing.
     *    attr(href) is what actually resolves.
     */
    css += `
/* TOC. target-counter is resolved by paged.js after each page is laid out. */
.wp-toc { break-after: page; }
.wp-toc ol { list-style: none; padding-left: 0; }
.wp-toc ol ol { padding-left: 1.5em; }
.wp-toc li { margin: 0.15em 0; }
.wp-toc a {
  display: flex;
  align-items: baseline;
  gap: 0.4em;
  text-decoration: none;
  color: var(--wp-color-fg);
}
.wp-toc-label { flex: 0 1 auto; }
.wp-toc a::before {
  content: "";
  flex: 1 1 auto;
  border-bottom: 1px dotted var(--wp-color-border);
  transform: translateY(-0.25em);
}
.wp-toc a::after {
  content: target-counter(attr(href), page);
  flex: 0 0 auto;
  color: var(--wp-color-fg-muted);
  font-variant-numeric: tabular-nums;
}
`;
  }

  if (layout.watermark.text) {
    /*
     * Attached to .pagedjs_page_content rather than .pagedjs_page: paged.js
     * uses ::before/::after on the page element itself for its own margin
     * boxes, and overwriting them breaks header/footer rendering.
     */
    css += `
.pagedjs_page_content::before {
  content: ${cssString(layout.watermark.text)};
  position: absolute;
  top: 50%;
  left: 50%;
  transform: translate(-50%, -50%) rotate(-45deg);
  font-family: var(--wp-font-family-sans);
  font-size: 100pt;
  font-weight: 700;
  color: var(--wp-color-fg);
  opacity: ${layout.watermark.opacity};
  z-index: 0;
  pointer-events: none;
  white-space: nowrap;
  -webkit-print-color-adjust: exact;
  print-color-adjust: exact;
}
.pagedjs_page_content > * { position: relative; z-index: 1; }
`;
    if (!layout.watermark.showInPreview) {
      // Screen-only suppression; print still stamps it.
      css += `@media screen {
  .paginator-output .pagedjs_page_content::before { content: none; }
}
`;
    }
  }

  return css;
}

/*
 * Printing paged.js output requires the BROWSER's page margin to be zero.
 *
 * paged.js consumes the @page margin itself: it insets the content inside each
 * .pagedjs_page box and hands us sheets that are already correctly laid out. If
 * the browser then applies the same 25mm again, every sheet is inset twice, the
 * boxes no longer divide evenly into browser pages, and the accumulated drift
 * emits a blank page at the end of every document.
 *
 * Appended after the generated @page rule so it wins the cascade, and scoped to
 * print so the on-screen preview keeps showing real margins.
 */
const PRINT_MARGIN_RESET = `
@media print {
  @page { margin: 0; }
}
`;

/** Mirrors the generated CSS into the document so it is live and inspectable. */
export function applyLayoutCSS(layout, opts = {}) {
  if (typeof document === 'undefined') return '';
  const css = generateLayoutCSS(layout, opts) + PRINT_MARGIN_RESET;
  let el = document.getElementById(LAYOUT_STYLE_ID);
  if (!el) {
    el = document.createElement('style');
    el.id = LAYOUT_STYLE_ID;
    document.head.appendChild(el);
  }
  if (el.textContent !== css) el.textContent = css;
  return css;
}
